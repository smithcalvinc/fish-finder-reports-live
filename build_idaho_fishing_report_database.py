#!/usr/bin/env python3
"""
Create the Fish Finder Outdoors statewide fishing-report search database.

The script combines:
1. The verified public-water and access-point database generated by
   build_idaho_public_fishing_access.py.
2. Current Idaho Fish and Game fishing/stocking updates.
3. Current Idaho reports published by established fishing websites.
4. Public social-media reports intentionally entered in
   data/public_social_reports.csv.

Facebook Groups are not scraped. Meta removed the Groups API and public Page
content requires approved API access. A public Facebook post can still be
included safely by adding its public URL and a short original summary to the
CSV template.

Outputs:
  data/idaho_fishing_report_database.json
  data/idaho_fishing_report_database.js
  data/idaho_fishing_report_database.csv
  data/idaho_fishing_report_summary.csv
  data/fishing_report_build_report.json
"""

